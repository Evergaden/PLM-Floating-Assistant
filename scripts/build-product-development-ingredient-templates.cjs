const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const outputPath = path.join(root, 'src', 'product-development-ingredient-templates.module.js');
const templates = [
  {
    id: 'human-builtin',
    kind: 'human',
    label: '人类食品成分表',
    fileName: '人类食品成分表1216.xlsx',
    source: path.join(root, 'src', 'assets', 'product-development-human-ingredient-template.xlsx'),
  },
  {
    id: 'pet-builtin',
    kind: 'pet',
    label: '宠物食品成分表',
    fileName: '宠物食品成分表1模板.xlsx',
    source: path.join(root, 'src', 'assets', 'product-development-pet-ingredient-template.xlsx'),
  },
];

function chunks(value, size) {
  const result = [];
  for (let index = 0; index < value.length; index += size) result.push(value.slice(index, index + size));
  return result;
}

const lines = [
  '// Generated from the supplied ingredient table workbooks. Do not edit this file by hand.',
  '  const PRODUCT_DEVELOPMENT_INGREDIENT_TEMPLATES = Object.freeze([',
];
templates.forEach((template, index) => {
  const base64 = fs.readFileSync(template.source).toString('base64');
  const encodedChunks = chunks(base64, 12000).map((chunk) => '      ' + JSON.stringify(chunk)).join(',\n');
  lines.push('    Object.freeze({');
  lines.push('      id: ' + JSON.stringify(template.id) + ',');
  lines.push('      kind: ' + JSON.stringify(template.kind) + ',');
  lines.push('      label: ' + JSON.stringify(template.label) + ',');
  lines.push('      fileName: ' + JSON.stringify(template.fileName) + ',');
  lines.push('      base64: [\n' + encodedChunks + '\n      ].join(\'\'),');
  lines.push('    })' + (index === templates.length - 1 ? '' : ','));
});
lines.push('  ]);');
fs.writeFileSync(outputPath, lines.join('\n') + '\n', 'utf8');
console.log('Wrote ' + path.relative(root, outputPath));
