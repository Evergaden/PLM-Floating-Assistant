// DOM-only long-press/hover navigation checks. Does not drive an installed script.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const { parseHTML } = require(process.env.PLM_DOM_MODULE || '../tmp/sku-render-check/node_modules/linkedom');
const source = fs.readFileSync(path.join(__dirname, '../src/product-development/pd-task-sync.module.js'), 'utf8');
const { document, window } = parseHTML('<html><body><div id="panel"><div class="pfh-detail-scroll"><nav><button data-product-development-tab="detail">详情</button></nav><section class="pfh-product-development-task-local-meta"></section><section><header class="pfh-product-development-product-form-header"></header></section><article data-material-card="box"></article></div></div></body></html>');
const panel = document.getElementById('panel');
const tabs = panel.querySelector('nav');
const trigger = tabs.querySelector('button');
const scroll = panel.querySelector('.pfh-detail-scroll');
const local = panel.querySelector('.pfh-product-development-task-local-meta');
const product = panel.querySelector('.pfh-product-development-product-form-header').closest('section');
const box = panel.querySelector('[data-material-card="box"]');
window.HTMLElement.prototype.getBoundingClientRect = () => ({ left: 0, top: 0, bottom: 40, width: 180, height: 130 });
panel.getBoundingClientRect = () => ({ left: 0, top: 0, width: 700, height: 800 });
tabs.getBoundingClientRect = () => ({ height: 42 });
scroll.getBoundingClientRect = () => ({ top: 0 });
scroll.scrollTop = 0;
local.getBoundingClientRect = () => ({ top: 200 - scroll.scrollTop });
product.getBoundingClientRect = () => ({ top: 800 - scroll.scrollTop });
box.getBoundingClientRect = () => ({ top: 1600 - scroll.scrollTop });
const timers = new Map();
let timerId = 0;
const state = { view: 'productDevelopmentTasks', productDevelopmentTaskView: 'detail' };
const context = vm.createContext({ document, state, window: { setTimeout: (fn, delay) => { timers.set(++timerId, { fn, delay }); return timerId; }, clearTimeout: (id) => timers.delete(id) } });
const start = source.indexOf('  function closeProductDevelopmentDetailJumpMenu(');
vm.runInContext(source.slice(start, source.indexOf('  function normalizeProductDevelopmentCachedTask(', start)), context);
const fire = (node, type, props = {}) => {
  const event = new window.Event(type, { bubbles: true, cancelable: true });
  Object.assign(event, props);
  node.dispatchEvent(event);
  return event;
};
const runTimer = (delay) => {
  const entry = Array.from(timers).find(([, timer]) => timer.delay === delay);
  assert.ok(entry, 'Expected timer ' + delay);
  timers.delete(entry[0]); entry[1].fn();
};
context.setupProductDevelopmentDetailJump(panel, tabs);
context.setupProductDevelopmentDetailJump(panel, tabs);
fire(trigger, 'pointerdown', { button: 0 });
assert.equal(Array.from(timers.values()).filter((timer) => timer.delay === 350).length, 1, 'Setup does not duplicate listeners');
fire(document, 'pointerup');
assert.equal(Array.from(timers.values()).some((timer) => timer.delay === 350), false);
assert.equal(fire(trigger, 'click').defaultPrevented, false, 'A short click retains ordinary tab navigation');
runTimer(0);

fire(trigger, 'pointerdown', { button: 0 });
runTimer(350);
let menu = panel.querySelector('.pfh-development-detail-jump');
assert.ok(menu);
assert.deepEqual(Array.from(menu.querySelectorAll('button'), (node) => node.textContent), ['产品本地填写', '填写建品信息', '纸盒']);
assert.equal(trigger.getAttribute('aria-expanded'), 'true');
const options = menu.querySelectorAll('button');
fire(options[1], 'pointerover', { relatedTarget: null });
assert.equal(scroll.scrollTop, 746, 'Hover jumps directly to product form below the sticky tabs');
fire(options[2], 'pointerover', { relatedTarget: options[1] });
assert.equal(scroll.scrollTop, 1546, 'Moving to the next menu item jumps again without clicking');
fire(document, 'pointerup');
assert.equal(fire(trigger, 'click').defaultPrevented, true, 'Releasing a long press cannot re-render the details tab');
runTimer(0);
context.closeProductDevelopmentDetailJumpMenu(panel);
assert.equal(trigger.getAttribute('aria-expanded'), 'false');

fire(trigger, 'pointerenter', { pointerType: 'mouse' });
runTimer(450);
menu = panel.querySelector('.pfh-development-detail-jump');
assert.ok(menu, 'Dwell opens the same menu');
fire(menu, 'pointerenter');
fire(document.body, 'pointerdown');
assert.equal(panel.querySelector('.pfh-development-detail-jump'), null, 'An outside press dismisses the menu');
box.remove();
fire(trigger, 'pointerenter', { pointerType: 'mouse' });
runTimer(450);
assert.equal(panel.querySelector('[data-development-detail-jump="box"]').disabled, true, 'Unavailable sections cannot jump to unrelated content');
context.closeProductDevelopmentDetailJumpMenu(panel);
state.productDevelopmentTaskView = 'copywriting';
fire(trigger, 'pointerenter', { pointerType: 'mouse' });
runTimer(450);
assert.equal(panel.querySelector('.pfh-development-detail-jump'), null, 'Other development tabs do not open a stale details menu');
console.log('Development details menu: hold/dwell, hover-only section jumps, release suppression, short click, dismissal and unavailable targets passed');
