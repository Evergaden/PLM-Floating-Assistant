const fs = require('node:fs');
const path = require('node:path');

function parseCsv(text) {
  const rows = [];
  let row = [];
  let cell = '';
  let quoted = false;
  for (let index = 0; index < text.length; index += 1) {
    const char = text[index];
    if (quoted) {
      if (char === '"' && text[index + 1] === '"') {
        cell += '"';
        index += 1;
      } else if (char === '"') {
        quoted = false;
      } else {
        cell += char;
      }
    } else if (char === '"') {
      quoted = true;
    } else if (char === ',') {
      row.push(cell);
      cell = '';
    } else if (char === '\n') {
      row.push(cell.replace(/\r$/, ''));
      rows.push(row);
      row = [];
      cell = '';
    } else {
      cell += char;
    }
  }
  if (cell || row.length) {
    row.push(cell.replace(/\r$/, ''));
    rows.push(row);
  }
  return rows;
}

function clean(value) {
  return String(value || '').replace(/\u00a0/g, ' ').replace(/\r\n?/g, '\n').trim();
}

function parseRepresentative(value) {
  const result = { company: '', address: '', contact: '', phone: '', postal_code: '' };
  const labels = [
    ['company', /公司名\s*[：:]\s*/],
    ['address', /地址\s*[：:]\s*/],
    ['contact', /联系人\s*[：:]\s*/],
    ['phone', /电话\s*[：:]\s*/],
    ['postal_code', /(?:邮政编码|邮编)\s*[：:]\s*/],
  ];
  const text = clean(value);
  labels.forEach(([key, pattern], index) => {
    const match = pattern.exec(text);
    if (!match) return;
    const start = match.index + match[0].length;
    let end = text.length;
    labels.slice(index + 1).forEach(([, nextPattern]) => {
      const nextMatch = nextPattern.exec(text.slice(start));
      if (nextMatch && start + nextMatch.index < end) end = start + nextMatch.index;
    });
    result[key] = clean(text.slice(start, end));
  });
  return result;
}

function findColumn(headers, predicate) {
  const index = headers.findIndex((header) => predicate(clean(header)));
  if (index < 0) throw new Error('Missing CSV column');
  return index;
}

const csvPath = process.argv[2];
if (!csvPath) throw new Error('Usage: npm run brands:import -- "C:\\path\\brands.csv"');

const root = path.resolve(__dirname, '..');
const runtimePath = path.join(root, 'static', 'assets', 'v1', 'runtime-data.json');
const seedPath = path.join(root, 'src', 'brand-compliance-seed.js');
const rows = parseCsv(fs.readFileSync(csvPath, 'utf8'));
const headers = rows.shift() || [];
const columns = {
  brand: findColumn(headers, (value) => value === '品牌'),
  distributedBy: findColumn(headers, (value) => value === '对应公司'),
  address: findColumn(headers, (value) => value === '对应地址'),
  eu: findColumn(headers, (value) => value.includes('欧代地址EU REP')),
  uk: findColumn(headers, (value) => value.includes('英代地址UK REP')),
  us: findColumn(headers, (value) => value.includes('美代地址US REP')),
};
const imported = rows.map((row, sortOrder) => {
  const sourceBrand = clean(row[columns.brand]);
  const isJaysuingAlias = /^JAYSUING\//i.test(sourceBrand);
  return {
    brand: isJaysuingAlias ? 'JAYSUING' : sourceBrand,
    aliases: isJaysuingAlias ? [sourceBrand, sourceBrand.split('/').slice(1).join('/')].filter(Boolean) : [],
    distributed_by: clean(row[columns.distributedBy]),
    address: clean(row[columns.address]),
    eu_rep: parseRepresentative(row[columns.eu]),
    uk_rep: parseRepresentative(row[columns.uk]),
    us_rep: parseRepresentative(row[columns.us]),
    sort_order: sortOrder,
  };
}).filter((item) => item.brand);

const runtime = JSON.parse(fs.readFileSync(runtimePath, 'utf8'));
const currentByBrand = new Map((runtime.brands || []).map((item) => [clean(item.brand).toUpperCase(), item]));
runtime.brands = imported.map(({ aliases, sort_order, ...item }) => ({
  ...(currentByBrand.get(item.brand.toUpperCase()) || {}),
  ...item,
  ...(aliases.length ? { aliases } : {}),
}));
fs.writeFileSync(runtimePath, JSON.stringify(runtime));
fs.writeFileSync(
  seedPath,
  '// Generated by scripts/import-brand-compliance.cjs. Edit through the admin dashboard or re-import the source CSV.\n' +
    'export const BRAND_COMPLIANCE_SEED = ' + JSON.stringify(imported, null, 2) + ';\n'
);
console.log(`Imported ${imported.length} brands into runtime data and Worker seed.`);
