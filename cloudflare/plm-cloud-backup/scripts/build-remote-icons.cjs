#!/usr/bin/env node

const fs = require('node:fs');
const path = require('node:path');
const React = require('react');
const { renderToStaticMarkup } = require('react-dom/server');
const lucide = require('lucide-react');

const ICONS = {
  'arrow-right': 'ArrowRight',
  archive: 'Archive',
  check: 'Check',
  'chevron-right': 'ChevronRight',
  'circle-user-round': 'CircleUserRound',
  'clipboard-list': 'ClipboardList',
  'file-output': 'FileOutput',
  home: 'Home',
  plus: 'Plus',
  refresh: 'RefreshCw',
  scan: 'ScanLine',
  search: 'Search',
  settings: 'Settings2',
  shield: 'ShieldCheck',
  sparkles: 'Sparkles',
  upload: 'Upload',
  x: 'X',
};

const indexPath = path.resolve(__dirname, '..', 'static', 'remote', 'index.html');
const startMarker = '/* REMOTE_LUCIDE_ICONS_START */';
const endMarker = '/* REMOTE_LUCIDE_ICONS_END */';

function renderIcon(componentName) {
  const Component = lucide[componentName];
  if (!Component) throw new Error(`Unknown lucide-react icon: ${componentName}`);
  return renderToStaticMarkup(React.createElement(Component, {
    className: 'lucide-icon',
    size: '1em',
    strokeWidth: 2,
    'aria-hidden': 'true',
    focusable: 'false',
  }));
}

const rendered = Object.fromEntries(Object.entries(ICONS).map(([name, component]) => [name, renderIcon(component)]));
const runtime = `/* Generated by scripts/build-remote-icons.cjs. Do not hand-edit SVG paths. */
(() => {
  const ICONS = ${JSON.stringify(rendered, null, 2)};
  const api = {
    svg(name) {
      return ICONS[name] || ICONS.sparkles;
    },
    mount(root = document) {
      root.querySelectorAll('[data-icon]').forEach((node) => {
        const name = node.getAttribute('data-icon');
        node.innerHTML = api.svg(name);
        node.classList.add('ui-icon');
        node.setAttribute('aria-hidden', 'true');
      });
    },
  };
  window.PLMIcons = Object.freeze(api);
})();
`;

const currentIndex = fs.readFileSync(indexPath, 'utf8');
const start = currentIndex.indexOf(startMarker);
const end = currentIndex.indexOf(endMarker);
if (start < 0 || end < start) throw new Error('Missing Lucide icon markers in static/remote/index.html');
const generatedIndex = currentIndex.slice(0, start)
  + startMarker + '\n'
  + runtime.trimEnd() + '\n'
  + endMarker
  + currentIndex.slice(end + endMarker.length);

if (process.argv.includes('--check')) {
  if (currentIndex !== generatedIndex) {
    console.error(`Inline remote icon bundle is stale: ${path.relative(process.cwd(), indexPath)}`);
    process.exit(1);
  }
} else {
  fs.writeFileSync(indexPath, generatedIndex);
  console.log(`Generated inline icons in ${path.relative(process.cwd(), indexPath)}`);
}
