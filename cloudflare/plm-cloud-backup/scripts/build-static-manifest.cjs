const crypto = require('crypto');
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const assetRoot = path.join(root, 'static', 'assets');
const manifestPath = path.join(assetRoot, 'manifest.json');
const manifestModulePath = path.join(root, 'src', 'generated-asset-manifest.js');
const previous = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
const dataVersion = String(process.argv[2] || previous.dataVersion || '').trim();
if (!dataVersion) throw new Error('Pass a data version, for example: npm run assets:manifest -- 2026-07-19.2');

function describeAsset(relativePath) {
  const data = fs.readFileSync(path.join(assetRoot, relativePath));
  return {
    path: relativePath,
    bytes: data.length,
    sha256: crypto.createHash('sha256').update(data).digest('hex'),
  };
}

const definitions = {
  runtimeData: 'v1/runtime-data.json',
  excelTemplate: 'v1/excel-template.xlsx',
  icons: 'v1/icons.json',
  uiStyles: 'v15/ui-2.5.200.css',
};
const assets = {};
for (const [name, relativePath] of Object.entries(definitions)) {
  assets[name] = describeAsset(relativePath);
}
assets.uiStyleVersions = Object.fromEntries(
  fs.readdirSync(path.join(assetRoot, 'v1'))
    .map((fileName) => ({ fileName, match: /^ui-(\d+\.\d+\.\d+)\.css$/.exec(fileName) }))
    .filter((entry) => entry.match)
    .sort((left, right) => left.match[1].localeCompare(right.match[1], undefined, { numeric: true }))
    .map((entry) => [entry.match[1], describeAsset('v1/' + entry.fileName)]),
);
const currentUiVersionMatch = /ui-(\d+\.\d+\.\d+)\.css$/.exec(definitions.uiStyles);
if (currentUiVersionMatch) assets.uiStyleVersions[currentUiVersionMatch[1]] = assets.uiStyles;

const manifest = {
  schemaVersion: 1,
  dataVersion,
  minimumClientVersion: previous.minimumClientVersion || '2.5.103',
  assets,
};
fs.writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + '\n');
fs.writeFileSync(
  manifestModulePath,
  `// Generated by scripts/build-static-manifest.cjs.\nexport const STATIC_ASSET_MANIFEST = ${JSON.stringify(manifest, null, 2)};\n`,
);
console.log(`Updated ${path.relative(root, manifestPath)} to ${dataVersion}`);
console.log(`Updated ${path.relative(root, manifestModulePath)} to ${dataVersion}`);
